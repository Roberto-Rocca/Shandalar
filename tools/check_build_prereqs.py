#!/usr/bin/env python3
"""Read-only preflight for the historical ManalinkEh.dll build environment."""

import argparse
import re
import shutil
import subprocess
from pathlib import Path

SOURCE_FILES = (
    "src/Makefile",
    "src/Makefile-common",
    "src/Makefile-targets",
    "src/ManalinkEh.asm",
    "src/ManalinkEh.def",
    "src/manalink.lds",
    "src/defs.h",
)
DATA_FILES = (
    "magic_updater/Manalink.csv",
    "magic_updater/ct_all.csv",
)
TOOLS = ("make", "gcc", "g++", "yasm", "dlltool", "objcopy")


def inspect_repository(root):
    failures = 0
    for relative_path in (*SOURCE_FILES, *DATA_FILES):
        found = (root / relative_path).is_file()
        print(f"{'OK     ' if found else 'MANCANTE'}  {relative_path}")
        failures += not found

    # Generated by csv2dat.exe; an older generated copy is in Program/src.
    header = root / "src/card_id.h"
    backup_header = root / "Program/src/card_id.h"
    if header.is_file():
        print("OK       src/card_id.h (generato)")
    elif backup_header.is_file():
        print("DA COPIARE src/card_id.h: disponibile Program/src/card_id.h")
        print("           Prima di compilare: cp Program/src/card_id.h src/card_id.h")
        failures += 1
    else:
        print("MANCANTE src/card_id.h (nessuna copia individuata)")
        failures += 1

    generator_candidates = (
        root / "magic_updater/csv2dat.exe",
        root / "csv2dat.exe",
    )
    generator_available = any(path.is_file() for path in generator_candidates)
    print(f"{'OK       ' if generator_available else 'NOTA     '} csv2dat.exe "
          "(serve per rigenerare il database, non per compilare se card_id.h e' presente)")
    return failures


def inspect_toolchain():
    failures = 0
    for executable in TOOLS:
        resolved = shutil.which(executable)
        print(f"{'OK     ' if resolved else 'MANCANTE'}  {executable}: {resolved or 'non trovato nel PATH'}")
        failures += not bool(resolved)

    compiler = shutil.which("gcc")
    if compiler:
        try:
            machine = subprocess.run(
                [compiler, "-dumpmachine"],
                check=True, capture_output=True, text=True, timeout=10,
            ).stdout.strip().lower()
        except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
            machine = ""
        valid = ("mingw" in machine and bool(re.match(r"i[3-6]86", machine)))
        print(f"{'OK     ' if valid else 'NON ADATTO'}  target gcc: {machine or 'non determinabile'} (richiesto MinGW 32 bit)")
        failures += not valid
    return failures


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Directory principale del repository (default: automatico)",
    )
    args = parser.parse_args()
    root = args.root.resolve()
    print(f"Repository: {root}")
    print("\n[File di progetto e dati]")
    missing = inspect_repository(root)
    print("\n[Toolchain]")
    missing += inspect_toolchain()
    print(f"\nRisultato: {missing} requisito/i non soddisfatto/i.")
    if missing:
        print("Compilazione non ancora verificabile. Nessun file e' stato modificato.")
    else:
        print("Prerequisiti statici presenti; compilazione e funzionamento ancora da testare.")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
